/**
 * English / Dutch. The app's own texts are written in English; Dutch is a DISPLAY-ONLY layer on top: [Text] below looks every text up in the Dutch word list
 * (I18nWords.kt, generated by tools/gen_i18n.py from the same list the landing page uses) and in the sentence patterns underneath, at the moment it is drawn.
 * Nothing but what is shown changes: setting keys and values, what is sent to the robot or the backend, and the language Jarvis speaks all stay as they are.
 * The chosen language is kept in the app's own preferences only.
 */
enum class Lang(val code: String) { EN("en"), NL("nl") }

object I18n {
    var lang by mutableStateOf(Lang.EN)
        private set

    /** Called when the person picks a language, so the view model can remember it. */
    var onChange: (Lang) -> Unit = {}

    fun restore(code: String?) { lang = if (code == "nl") Lang.NL else Lang.EN }

    fun choose(l: Lang) {
        if (l == lang) return
        lang = l
        onChange(l)
    }
}

private fun dutchDuration(s: String, wake: Boolean): String {   // "for 1 hr 30 min" / "until you press the BOOT button"
    if (s == "until you press the BOOT button") return "tot je op de BOOT-knop drukt"
    val m = Regex("^for (?:(\\d+) hrs?)?(?: )?(?:(\\d+) min)?$").matchEntire(s) ?: return s
    val h = m.groupValues[1]
    val min = m.groupValues[2]
    return (if (wake) "na " else "gedurende ") + (if (h.isNotEmpty()) "$h uur" else "") + (if (h.isNotEmpty() && min.isNotEmpty()) " " else "") + (if (min.isNotEmpty()) "$min min" else "")
}

