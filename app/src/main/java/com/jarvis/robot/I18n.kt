/** [s] in the chosen language: English texts come back untouched, Dutch ones are looked up (whole text first, then the sentence patterns). */
fun tr(s: String): String {
    if (I18n.lang == Lang.EN || s.isBlank()) return s
    val lead = s.takeWhile { it.isWhitespace() }
    val trail = s.takeLastWhile { it.isWhitespace() }
    val core = s.trim()
    I18nNl.words[core]?.let { return lead + it + trail }
    // headings the app writes in capitals ("WEATHER", "ROBOT SETTINGS"): look up the plain text, answer in capitals
    if (core == core.uppercase() && core.any { it.isLetter() }) {
        val plain = core.lowercase().replaceFirstChar { it.uppercase() }
        I18nNl.words[plain]?.let { return lead + it.uppercase() + trail }
    }
    for ((re, f) in RULES) {
        val m = re.matchEntire(core) ?: continue
        val r = f(m) ?: continue
        return lead + r + trail
    }
    return s
}

/** The same as material3's Text for a String, but the text goes through [tr] first; every screen uses this one. */
@Composable
fun Text(
    text: String,
    modifier: Modifier = Modifier,
    color: Color = Color.Unspecified,
    fontSize: TextUnit = TextUnit.Unspecified,
    fontStyle: FontStyle? = null,
    fontWeight: FontWeight? = null,
    fontFamily: FontFamily? = null,
    letterSpacing: TextUnit = TextUnit.Unspecified,
    textDecoration: TextDecoration? = null,
    textAlign: TextAlign? = null,
    lineHeight: TextUnit = TextUnit.Unspecified,
    overflow: TextOverflow = TextOverflow.Clip,
    softWrap: Boolean = true,
    maxLines: Int = Int.MAX_VALUE,
    minLines: Int = 1,
    onTextLayout: ((TextLayoutResult) -> Unit)? = null,
    style: TextStyle = LocalTextStyle.current,
) {
    androidx.compose.material3.Text(
        text = tr(text), modifier = modifier, color = color, fontSize = fontSize, fontStyle = fontStyle, fontWeight = fontWeight, fontFamily = fontFamily,
        letterSpacing = letterSpacing, textDecoration = textDecoration, textAlign = textAlign, lineHeight = lineHeight, overflow = overflow, softWrap = softWrap,
        maxLines = maxLines, minLines = minLines, onTextLayout = onTextLayout, style = style,
    )
}
